// Regenerates lib/app/core/values/lucide_icons.dart: a `LucideIcons` class
// holding only the Lucide icons the app actually uses, plus the bundled font.
//
//   dart run tool/generate_lucide_icons.dart
//
// Run it after using a new `LucideIcons.<name>` anywhere under lib/.
// (Browse names at https://lucide.dev/icons — use the camelCase form, e.g.
// `circle-check` → `LucideIcons.circleCheck`.)
//
// Why not import package:lucide_icons_flutter directly? Its `LucideIcons`
// class declares ~30,000 constants (every icon × 7 stroke weights × RTL), which
// overflows the JS stack when the debug web compiler (DDC) initialises it, and
// the package bundles six extra stroke-weight fonts (~2.9 MB) that every web
// page load would download. The package stays a dev_dependency and is the
// source of truth for names, codepoints and the font file.
import 'dart:convert';
import 'dart:io';

const _package = 'lucide_icons_flutter';
const _outFile = 'lib/app/core/values/lucide_icons.dart';
const _fontOut = 'assets/fonts/lucide/lucide.ttf';
const _licenseOut = 'assets/fonts/lucide/LICENSE';

void main() {
  final pkgRoot = _packageRoot();
  final source =
      File('${pkgRoot.path}/lib/lucide_icons.dart').readAsStringSync();

  // Default (2px stroke) family only: `static const IconData mail = const
  // IconData(58757, fontFamily: 'Lucide', fontPackage: 'lucide_icons_flutter');`
  final defRe = RegExp(
    r"static const IconData (\w+) = const IconData\((\d+),\s*"
    r"fontFamily: 'Lucide',\s*fontPackage: 'lucide_icons_flutter'\);",
  );
  final codepoints = {
    for (final m in defRe.allMatches(source)) m.group(1)!: int.parse(m.group(2)!),
  };

  final used = <String>{};
  final useRe = RegExp(r'\bLucideIcons\.(\w+)');
  for (final f in Directory('lib').listSync(recursive: true)) {
    if (f is! File || !f.path.endsWith('.dart') || f.path.endsWith(_outFile)) {
      continue;
    }
    for (final m in useRe.allMatches(f.readAsStringSync())) {
      used.add(m.group(1)!);
    }
  }

  final unknown = used.where((n) => !codepoints.containsKey(n)).toList()..sort();
  if (unknown.isNotEmpty) {
    stderr.writeln('Unknown Lucide icon names: ${unknown.join(', ')}');
    exitCode = 1;
    return;
  }

  final names = used.toList()..sort();
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/generate_lucide_icons.dart — do not edit by hand.')
    ..writeln('// Icons: Lucide (ISC, https://lucide.dev) via the $_package package (MIT).')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// The Lucide icons used by the app (2px stroke, font family `Lucide`).')
    ..writeln('/// To add one, reference `LucideIcons.<name>` and re-run the generator.')
    ..writeln('@staticIconProvider')
    ..writeln('class LucideIcons {')
    ..writeln('  LucideIcons._();')
    ..writeln();
  for (final n in names) {
    final hex = codepoints[n]!.toRadixString(16);
    out.writeln("  static const IconData $n = IconData(0x$hex, fontFamily: 'Lucide');");
  }
  out.writeln('}');
  File(_outFile).writeAsStringSync(out.toString());

  final font = File('${pkgRoot.path}/assets/lucide.ttf');
  File(_fontOut).parent.createSync(recursive: true);
  font.copySync(_fontOut);
  File(_licenseOut).writeAsStringSync(
    'Lucide icon font — icons by Lucide Contributors (ISC License,\n'
    'https://github.com/lucide-icons/lucide/blob/main/LICENSE), packaged by\n'
    '$_package (MIT License):\n\n'
    '${File('${pkgRoot.path}/LICENSE').readAsStringSync().trim()}\n',
  );

  stdout.writeln('Wrote ${names.length} icons to $_outFile and the font to $_fontOut');
}

/// Resolves the package directory from .dart_tool/package_config.json.
Directory _packageRoot() {
  final config = File('.dart_tool/package_config.json');
  if (!config.existsSync()) {
    throw StateError('Run `flutter pub get` first (no package_config.json).');
  }
  final json = jsonDecode(config.readAsStringSync()) as Map<String, dynamic>;
  final entry = (json['packages'] as List)
      .cast<Map<String, dynamic>>()
      .firstWhere((p) => p['name'] == _package,
          orElse: () => throw StateError('$_package is not in pubspec.yaml'));
  final uri = config.parent.uri.resolve(entry['rootUri'] as String);
  return Directory.fromUri(uri);
}
